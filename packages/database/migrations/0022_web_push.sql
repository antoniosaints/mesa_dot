CREATE TABLE push_settings (
  id CHAR(36) NOT NULL PRIMARY KEY,
  tenant_id CHAR(36) NOT NULL,
  establishment_id CHAR(36) NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT FALSE,
  enabled_since DATETIME(3) NULL,
  rules JSON NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  updated_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3) ON UPDATE CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_push_settings_unit (tenant_id, establishment_id),
  CONSTRAINT fk_push_settings_unit FOREIGN KEY (tenant_id, establishment_id) REFERENCES establishments (tenant_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE push_subscriptions (
  id CHAR(36) NOT NULL PRIMARY KEY,
  tenant_id CHAR(36) NOT NULL,
  establishment_id CHAR(36) NOT NULL,
  user_id CHAR(36) NOT NULL,
  staff_session_id CHAR(36) NOT NULL,
  endpoint_hash CHAR(64) NOT NULL,
  credentials TEXT NOT NULL,
  vapid_key_hash CHAR(64) NOT NULL,
  origin VARCHAR(255) NOT NULL,
  surface ENUM('admin','waiter','kitchen') NOT NULL,
  device_name VARCHAR(100) NOT NULL,
  enabled BOOLEAN NOT NULL DEFAULT TRUE,
  expires_at DATETIME(3) NULL,
  last_seen_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_push_subscription (tenant_id, establishment_id, user_id, endpoint_hash),
  KEY ix_push_endpoint (endpoint_hash),
  KEY ix_push_session (staff_session_id),
  CONSTRAINT fk_push_subscription_unit FOREIGN KEY (tenant_id, establishment_id) REFERENCES establishments (tenant_id, id),
  CONSTRAINT fk_push_subscription_user FOREIGN KEY (user_id) REFERENCES users (id),
  CONSTRAINT fk_push_subscription_session FOREIGN KEY (tenant_id, establishment_id, staff_session_id) REFERENCES staff_sessions (tenant_id, establishment_id, id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE push_deliveries (
  id CHAR(36) NOT NULL PRIMARY KEY,
  tenant_id CHAR(36) NOT NULL,
  establishment_id CHAR(36) NOT NULL,
  event_id CHAR(36) NOT NULL,
  subscription_id CHAR(36) NULL,
  event_key VARCHAR(60) NOT NULL,
  payload JSON NOT NULL,
  state ENUM('PENDING','SENT','SKIPPED','EXPIRED','FAILED') NOT NULL DEFAULT 'PENDING',
  attempts INT NOT NULL DEFAULT 0,
  next_attempt_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  expires_at DATETIME(3) NOT NULL,
  sent_at DATETIME(3) NULL,
  last_error VARCHAR(60) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_push_event_subscription (event_id, subscription_id),
  KEY ix_push_dispatch (state, next_attempt_at),
  KEY ix_push_unit_created (tenant_id, establishment_id, created_at),
  CONSTRAINT fk_push_delivery_unit FOREIGN KEY (tenant_id, establishment_id) REFERENCES establishments (tenant_id, id),
  CONSTRAINT fk_push_delivery_event FOREIGN KEY (tenant_id, establishment_id, event_id) REFERENCES outbox_events (tenant_id, establishment_id, id),
  CONSTRAINT fk_push_delivery_subscription FOREIGN KEY (subscription_id) REFERENCES push_subscriptions (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

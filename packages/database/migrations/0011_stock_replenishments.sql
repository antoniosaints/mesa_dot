CREATE TABLE IF NOT EXISTS stock_replenishments (
  id CHAR(36) NOT NULL PRIMARY KEY,
  tenant_id CHAR(36) NOT NULL,
  establishment_id CHAR(36) NOT NULL,
  supplier_name VARCHAR(160) NULL,
  invoice_number VARCHAR(80) NULL,
  freight DECIMAL(14,2) NOT NULL DEFAULT 0,
  discount DECIMAL(14,2) NOT NULL DEFAULT 0,
  subtotal DECIMAL(16,2) NULL,
  total DECIMAL(16,2) NULL,
  item_count SMALLINT UNSIGNED NOT NULL,
  notes VARCHAR(500) NULL,
  created_by CHAR(36) NOT NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_replenishment_scope (tenant_id,establishment_id,id),
  KEY idx_replenishment_date (tenant_id,establishment_id,created_at,id),
  FOREIGN KEY (tenant_id,establishment_id) REFERENCES establishments(tenant_id,id),
  FOREIGN KEY (created_by) REFERENCES users(id),
  CHECK (freight >= 0 AND discount >= 0),
  CHECK (subtotal IS NULL OR subtotal >= 0),
  CHECK (total IS NULL OR total >= 0),
  CHECK (item_count BETWEEN 1 AND 100)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
CREATE TABLE IF NOT EXISTS stock_replenishment_items (
  id CHAR(36) NOT NULL PRIMARY KEY,
  tenant_id CHAR(36) NOT NULL,
  establishment_id CHAR(36) NOT NULL,
  replenishment_id CHAR(36) NOT NULL,
  balance_id CHAR(36) NOT NULL,
  product_name VARCHAR(160) NOT NULL,
  variant_name VARCHAR(100) NULL,
  location_name VARCHAR(100) NOT NULL,
  quantity DECIMAL(14,3) NOT NULL,
  physical_before DECIMAL(14,3) NOT NULL,
  physical_after DECIMAL(14,3) NOT NULL,
  unit_cost DECIMAL(14,2) NULL,
  line_total DECIMAL(16,2) NULL,
  created_at DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  UNIQUE KEY uq_replenishment_balance (tenant_id,establishment_id,replenishment_id,balance_id),
  FOREIGN KEY (tenant_id,establishment_id,replenishment_id) REFERENCES stock_replenishments(tenant_id,establishment_id,id),
  FOREIGN KEY (tenant_id,establishment_id,balance_id) REFERENCES stock_balances(tenant_id,establishment_id,id),
  CHECK (quantity > 0 AND physical_before >= 0 AND physical_after >= physical_before),
  CHECK (unit_cost IS NULL OR unit_cost >= 0),
  CHECK (line_total IS NULL OR line_total >= 0)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
